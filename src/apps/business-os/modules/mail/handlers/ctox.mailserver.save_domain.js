// Fachlogik (hier): Pflichtfeld domain_name, Selektor-Rückfall `default`, SPF-/DMARC-Vorgaben.
// Fähigkeit (Kern): DKIM-Schlüssel erzeugen, stalwart_domains schreiben, öffentlichen Schlüssel ableiten →
// ctx.cap.mail.server.domain.save. CAP-3 #831 (caps/mail.rs server_payload "domain.save"): der Kern nimmt
// dkim_private_key nur als null an und erzeugt den Schlüssel selbst; ein von der App gelieferter Privatschlüssel
// wird abgewiesen. Deshalb lehnt der Handler ihn vor dem Kernaufruf ab (kein stilles Verwerfen) und die UI hat
// kein Feld dafür. Der private Schlüssel verlässt den Kern nie.
import { callCap, fail, payloadOf } from './_base.js';

export function normalizeDomain(payload) {
  const domainName = typeof payload.domain_name === 'string' ? payload.domain_name.trim() : '';
  let dkimSelector = (typeof payload.dkim_selector === 'string' ? payload.dkim_selector : 'default').trim();
  if (dkimSelector === '') dkimSelector = 'default';
  if (domainName === '') fail('invalid', 'domain_name is required');
  const suppliedKey = payload.dkim_private_key;
  if (suppliedKey != null && !(typeof suppliedKey === 'string' && suppliedKey.trim() === '')) {
    fail('invalid', 'dkim_private_key is generated by CTOX; a supplied private key is not accepted');
  }
  const nonEmpty = (value) => (typeof value === 'string' && value.trim() !== '' ? value.trim() : undefined);
  return {
    domain_name: domainName,
    dkim_selector: dkimSelector,
    spf_record: nonEmpty(payload.spf_record) ?? 'v=spf1 mx a ~all',
    dmarc_record: nonEmpty(payload.dmarc_record) ?? `v=DMARC1; p=none; rua=mailto:dmarc@${domainName}`,
  };
}

export default async function handle(command, ctx) {
  const domain = normalizeDomain(payloadOf(command));
  const saved = await callCap(ctx, 'mail.server.domain.save', {
    ...domain,
    dkim_private_key: null, // Kern erzeugt den Schlüssel (generate_dkim_private_key)
  });
  return {
    domain_name: domain.domain_name,
    dkim_selector: domain.dkim_selector,
    spf_record: domain.spf_record,
    dmarc_record: domain.dmarc_record,
    dkim_private_key_set: true,
    secret_value_revealed: false,
    dkim_public_key: saved?.dkim_public_key ?? null,
  };
}
