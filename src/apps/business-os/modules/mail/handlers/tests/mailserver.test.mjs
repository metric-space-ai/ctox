import test from 'node:test';
import assert from 'node:assert/strict';
import { createCtx, run } from './_ctx.mjs';

const CURRENT = {
  enabled: false, hostname: 'mail.example.org', bind_host: '127.0.0.1', smtp_port: 2525, imap_port: 1143,
  outbound_throttle_per_min: 60, max_connections: 32,
};
const caps = (extra = {}) => ({
  'mail.server.config.get': { runtime_config: CURRENT, domains: [], users: [] },
  'mail.server.runtime.save': { runtime_status: { running: true } },
  'mail.server.domain.save': { dkim_public_key: 'PUB' },
  ...extra,
});

test('get_config reicht das Kernergebnis durch', async () => {
  const ctx = createCtx({ caps: caps() });
  const out = await run(ctx, 'ctox.mailserver.get_config', {});
  assert.deepEqual(out.runtime_config, CURRENT);
  assert.equal(ctx.$.capsTo('mail.server.config.get').length, 1);
});

test('save_runtime: Rückfall auf aktuelle Werte, Slash am Ende entfernt', async () => {
  const ctx = createCtx({ caps: caps() });
  const out = await run(ctx, 'ctox.mailserver.save_runtime', { enabled: true, smtp_port: 25, hostname: '  ' });
  assert.equal(out.saved, true);
  assert.equal(out.runtime_config.enabled, true);
  assert.equal(out.runtime_config.smtp_port, 25);
  assert.equal(out.runtime_config.hostname, 'mail.example.org');
  assert.deepEqual(out.runtime_status, { running: true });
  assert.deepEqual(ctx.$.capsTo('mail.server.runtime.save')[0].args[0].settings, out.runtime_config);
});

test('save_runtime: Prüfregeln wie Rust, nichts gespeichert', async () => {
  const cases = [
    [{ smtp_port: 70000 }, 'smtp_port must be between 1 and 65535'],
    [{ imap_port: 0 }, 'ports must be greater than zero'],
    [{ smtp_port: 1143 }, 'SMTP and IMAP ports must differ'],
    [{ outbound_throttle_per_min: 0 }, 'outbound_throttle_per_min must be greater than zero'],
    [{ max_connections: 0 }, 'max_connections must be greater than zero'],
  ];
  for (const [payload, message] of cases) {
    const ctx = createCtx({ caps: caps() });
    await assert.rejects(run(ctx, 'ctox.mailserver.save_runtime', payload), { code: 'invalid', message });
    assert.equal(ctx.$.capsTo('mail.server.runtime.save').length, 0, message);
  }
});

test('save_runtime: tracking_base_url entfällt (§16.38 Nr. 5) – Wert wird ignoriert, nie an den Kern gegeben', async () => {
  for (const value of ['https://t.example.org', 'nope', 'https://u:p@x.example.org']) {
    const ctx = createCtx({ caps: caps({ 'mail.server.config.get': { runtime_config: { ...CURRENT, tracking_base_url: 'https://alt.example.org' }, domains: [], users: [] } }) });
    const out = await run(ctx, 'ctox.mailserver.save_runtime', { tracking_base_url: value });
    assert.equal('tracking_base_url' in out.runtime_config, false, value);
    assert.equal('tracking_base_url' in ctx.$.capsTo('mail.server.runtime.save')[0].args[0].settings, false, value);
  }
});

test('save_domain: Vorgaben für Selektor, SPF, DMARC; Schlüssel nie im Ergebnis', async () => {
  const ctx = createCtx({ caps: caps() });
  const out = await run(ctx, 'ctox.mailserver.save_domain', { domain_name: ' example.org ', dkim_selector: ' ' });
  assert.deepEqual(out, {
    domain_name: 'example.org', dkim_selector: 'default', spf_record: 'v=spf1 mx a ~all',
    dmarc_record: 'v=DMARC1; p=none; rua=mailto:dmarc@example.org', dkim_private_key_set: true,
    secret_value_revealed: false, dkim_public_key: 'PUB',
  });
  assert.equal(ctx.$.capsTo('mail.server.domain.save')[0].args[0].dkim_private_key, null);
  await assert.rejects(run(createCtx({ caps: caps() }), 'ctox.mailserver.save_domain', {}), { code: 'invalid', message: 'domain_name is required' });
});

test('save_domain: CAP-3 #831 – Privatschlüssel erzeugt der Kern; ein gelieferter Schlüssel wird ohne Kernaufruf abgewiesen', async () => {
  const ctx = createCtx({ caps: caps() });
  await assert.rejects(run(ctx, 'ctox.mailserver.save_domain', { domain_name: 'example.org', dkim_private_key: '-----BEGIN PRIVATE KEY-----x' }),
    { code: 'invalid', message: /generated by CTOX/ });
  assert.equal(ctx.$.capsTo('mail.server.domain.save').length, 0);
  // Leer/null (Altform der Outbound-Oberfläche) bleibt erlaubt und geht als null an den Kern.
  for (const empty of ['', '  ', null]) {
    const c = createCtx({ caps: caps() });
    await run(c, 'ctox.mailserver.save_domain', { domain_name: 'example.org', dkim_private_key: empty });
    assert.equal(c.$.capsTo('mail.server.domain.save')[0].args[0].dkim_private_key, null);
  }
});

test('delete_domain / delete_user / save_user', async () => {
  const ctx = createCtx({ caps: caps() });
  assert.deepEqual(await run(ctx, 'ctox.mailserver.delete_domain', { domain_name: 'example.org' }), { domain_name: 'example.org', deleted: true });
  assert.deepEqual(await run(ctx, 'ctox.mailserver.delete_user', { username: 'Ada@Example.org' }),
    { username: 'Ada@Example.org', communication_account_key: 'email:ada@example.org', deleted: true });
  // Kernvertrag: getrennte Routen mit nativer Payload (core-contract.mjs), kein mail.server.delete({kind,…}).
  assert.deepEqual(ctx.$.capsTo('mail.server.domain.delete').map((c) => c.args[0]), [{ domain_name: 'example.org' }]);
  assert.deepEqual(ctx.$.capsTo('mail.server.user.delete').map((c) => c.args[0]), [{ username: 'Ada@Example.org' }]);
  assert.equal(ctx.$.capsTo('mail.server.delete').length, 0);
  const saved = await run(ctx, 'ctox.mailserver.save_user', { username: 'Ada@Example.org', user_id: 'u1', password: 'leak' });
  assert.deepEqual(saved, { username: 'Ada@Example.org', communication_account_key: 'email:ada@example.org', owner_user_id: 'u1', saved: true });
  const call = ctx.$.capsTo('mail.server.user.save')[0].args[0];
  assert.deepEqual(call.password, { secret_intake: true }, 'Passwort nie aus dem Payload');
  assert.equal(JSON.stringify(call).includes('leak'), false);
  assert.equal(call.communication_account.metadata.mailbox_status, 'ready');
  const noOwner = await run(createCtx({ caps: caps() }), 'ctox.mailserver.save_user', { username: 'bob' });
  assert.equal(noOwner.owner_user_id, 'bob');
  await assert.rejects(run(createCtx(), 'ctox.mailserver.delete_user', {}), { code: 'invalid', message: 'username is required' });
  await assert.rejects(run(createCtx(), 'ctox.mailserver.save_user', { username: ' ' }), { code: 'invalid', message: 'username is required' });
});

