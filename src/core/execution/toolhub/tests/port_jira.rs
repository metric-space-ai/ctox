/// Live smoke test: read-only calls against the real instance.
/// `CTOX_TOOLHUB_LIVE_JIRA_TOKEN` must hold a bearer-usable credential; the test
/// is skipped silently when unset.
#[test]
#[ignore]
fn live_read_only() {
    let jira = Jira::default();
    for (tool, args) in [
        ("JIRA_GET_CURRENT_USER", json!({})),
        ("JIRA_LIST_PROJECTS", json!({"max_results": 5})),
        (
            "JIRA_SEARCH_ISSUES",
            json!({"jql": "order by created DESC", "max_results": 3}),
        ),
    ] {
        if let Some(r) = support::live(&jira, tool, args) {
            let out = r.expect("live call failed");
            assert!(!out.to_string().is_empty(), "{tool}: empty result");
        }
    }
}
