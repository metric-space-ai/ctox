#!/usr/bin/env node
// Origin: CTOX
// License: AGPL-3.0-only
// Generates the native constants and the browser validator for
// ctox.workjet.project_feed.v1 from the canonical fixture. `--check` rejects drift.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../../../../', import.meta.url));
const fixturePath = `${root}src/core/rxdb/tests/fixtures/workjet-project-feed-v1.json`;
const rustPath = `${root}src/core/business_os/workjet_project_feed_contract.generated.rs`;
const jsPath = `${root}src/apps/business-os/shared/workjet-project-feed-contract.generated.mjs`;
const fixture = JSON.parse(readFileSync(fixturePath, 'utf8'));
const { contract, limits, enums } = fixture;

const header = '// @generated by src/core/rxdb/tools/build_workjet_project_feed_contract.mjs; do not edit.\n';
const rustType = name => (['MAX_PAGE', 'DEFAULT_PAGE'].includes(name) ? 'u32' : name === 'MAX_FUTURE_MS' ? 'i64' : 'usize');
const rust = `${header}// Origin: CTOX\n// License: AGPL-3.0-only\n#![allow(dead_code)]\n`
  + `pub(crate) const CONTRACT_SCHEMA: &str = ${JSON.stringify(contract)};\n`
  + Object.entries(limits).map(([k, v]) => `pub(crate) const ${k}: ${rustType(k)} = ${v};\n`).join('')
  + Object.entries(enums).map(([k, v]) => `pub(crate) const ${k}: &[&str] = &[${v.map(x => JSON.stringify(x)).join(', ')}];\n`).join('');

const js = `${header}// Origin: CTOX\n// License: AGPL-3.0-only\n`
  + `export const PROJECT_FEED_SCHEMA = ${JSON.stringify(contract)};\n`
  + `export const PROJECT_FEED_LIMITS = Object.freeze(${JSON.stringify(limits)});\n`
  + `export const PROJECT_FEED_ENUMS = Object.freeze(${JSON.stringify(enums)});\n`
  + `const text = (v, max) => typeof v === 'string' && v.trim().length > 0 && [...v].length <= max;
const nullable = (v, check) => v === null || v === undefined || check(v);
const keys = (o, allowed) => o && typeof o === 'object' && !Array.isArray(o) && Object.keys(o).every(k => allowed.includes(k));
export function validateProjectFeedPost(post) {
  const L = PROJECT_FEED_LIMITS, E = PROJECT_FEED_ENUMS;
  const fields = ['post_id','project_id','kind','author_kind','author_thread','author_label','harness','headline','body','open_items','sources','action','thread_ref','occurred_at_ms'];
  if (!keys(post, fields)) return { ok: false, error: 'Feed post has unknown fields.' };
  const ok = text(post.post_id, 64) && text(post.project_id, L.MAX_ID)
    && E.KINDS.includes(post.kind) && E.AUTHOR_KINDS.includes(post.author_kind)
    && nullable(post.author_thread, v => text(v, L.MAX_ID)) && text(post.author_label, L.MAX_AUTHOR_LABEL)
    && nullable(post.harness, v => text(v, L.MAX_HARNESS)) && text(post.headline, L.MAX_HEADLINE)
    && text(post.body, L.MAX_BODY)
    && nullable(post.open_items, v => Array.isArray(v) && v.length <= L.MAX_OPEN_ITEMS && v.every(x => text(x, L.MAX_HEADLINE)))
    && Array.isArray(post.sources) && post.sources.length <= L.MAX_SOURCES
    && post.sources.every(s => keys(s, ['type','label','ref']) && E.SOURCE_TYPES.includes(s.type) && text(s.label, L.MAX_SOURCE_LABEL) && text(s.ref, L.MAX_REF))
    && nullable(post.action, a => keys(a, ['type','label_de','label_en','ref']) && E.ACTION_TYPES.includes(a.type) && text(a.label_de, L.MAX_ACTION_LABEL) && text(a.label_en, L.MAX_ACTION_LABEL) && text(a.ref, L.MAX_REF))
    && nullable(post.thread_ref, v => text(v, L.MAX_ID))
    && Number.isSafeInteger(post.occurred_at_ms) && post.occurred_at_ms > 0;
  return ok ? { ok: true } : { ok: false, error: 'Feed post violates ctox.workjet.project_feed.v1.' };
}
`;

const check = process.argv.includes('--check');
let drift = false;
for (const [path, content] of [[rustPath, rust], [jsPath, js]]) {
  let current = '';
  try { current = readFileSync(path, 'utf8'); } catch {}
  if (current === content) continue;
  if (check) { console.error(`drift: ${path}`); drift = true; } else writeFileSync(path, content);
}
for (const post of fixture.read_response.posts) {
  const { validateProjectFeedPost } = await import(`data:text/javascript,${encodeURIComponent(js)}`);
  const result = validateProjectFeedPost(post);
  if (!result.ok) { console.error(`fixture post ${post.post_id}: ${result.error}`); process.exitCode = 1; }
}
if (drift) process.exitCode = 1;
